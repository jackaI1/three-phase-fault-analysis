@pytest.fixture
def kirtley():
    return load_network("examples/kirtley.json")


@pytest.mark.parametrize(
    "fault,expected_012",
    [
        ("3ph", [0j, -6.67j, 0j]),
        ("lg", [-3j, -1.33j, -1.33j]),
        ("ll", [0j, -3.33j, 3.33j]),
        ("llg", [2.14j, -3.81j, 2.86j]),
    ],
)
def test_textbook_breaker_sequence_answers(kirtley, fault, expected_012):
    # Kirtley, ch. 4, section 4.6, Example of Fault Calculations.
    # These are published two-decimal answers, not outputs generated by this code.
    result = solve_fault(kirtley, "fault", fault)
    actual = phase_to_sequence(result.source_current_pu["breaker_B"])
    np.testing.assert_allclose(actual, expected_012, atol=0.005, rtol=0)


