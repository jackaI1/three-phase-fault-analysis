@pytest.mark.parametrize("fault", FAULT_TYPES)
@pytest.mark.parametrize("zf", [0j, 0.07 + 0.03j])
def test_fault_boundaries_and_kcl(fault, zf):
    network = load_network("examples/feeder.json")
    result = solve_fault(network, "plant", fault, zf)
    ia, ib, ic = result.phase_current_pu
    va, vb, vc = result.bus_voltage_pu["plant"]
    if fault == "3ph":
        np.testing.assert_allclose([va, vb, vc], zf * result.phase_current_pu, atol=1e-12)
    elif fault == "lg":
        np.testing.assert_allclose([ib, ic, va - zf * ia], 0, atol=1e-12)
    elif fault == "ll":
        np.testing.assert_allclose([ia, ib + ic, vb - vc - zf * ib], 0, atol=1e-12)
    else:
        np.testing.assert_allclose([ia, vb - vc, vb - zf * (ib + ic)], 0, atol=1e-12)
    np.testing.assert_allclose(
        result.branch_current_pu["main_feeder"], result.phase_current_pu, atol=1e-12
    )
    np.testing.assert_allclose(result.branch_current_pu["workshop_cable"], 0, atol=1e-12)
    np.testing.assert_allclose(
        result.source_current_pu["grid"], result.phase_current_pu, atol=1e-12
    )
    assert result.residual_current_a == pytest.approx(sum(result.phase_current_a), abs=1e-9)


@pytest.mark.parametrize("fault", FAULT_TYPES)
def test_ungrounded_faults(fault):
    net = Network(("bus",), (), (Source("s", "bus", None, 0.2j, 0.2j),), 10, 13.8)
    result = solve_fault(net, "bus", fault)
    assert abs(result.sequence_current_pu[0]) < 1e-12
    if fault == "lg":
        np.testing.assert_allclose(result.phase_current_pu, 0, atol=1e-12)
        assert abs(result.bus_voltage_pu["bus"][0]) < 1e-12
    if fault == "llg":
        np.testing.assert_allclose(
            result.phase_current_pu, solve_fault(net, "bus", "ll").phase_current_pu, atol=1e-12
        )


def test_series_network_thevenin_and_parallel_sources():
    network = load_network("examples/feeder.json")
    assert network.driving_column("workshop", 1)["workshop"] == pytest.approx(0.07 + 0.15j)
    fault = solve_fault(network, "workshop", "3ph")
    assert fault.phase_current_pu[0] == pytest.approx(1 / (0.07 + 0.15j))
    assert fault.base_current_a == pytest.approx(418.3697602823376)
    np.testing.assert_allclose(
        fault.branch_current_pu["main_feeder"],
        fault.branch_current_pu["workshop_cable"],
        atol=1e-12,
    )
    reverse = replace(network.branches[1], from_bus="workshop", to_bus="plant")
    reversed_net = replace(network, branches=(network.branches[0], reverse))
    np.testing.assert_allclose(
        solve_fault(reversed_net, "workshop", "3ph").branch_current_pu["workshop_cable"],
        -fault.branch_current_pu["workshop_cable"],
        atol=1e-12,
    )


def test_meshed_network_and_multiple_islands():
    net = Network(
        ("a", "b", "c", "d"),
        (
            Branch("ab", "a", "b", 0.3j, 0.1j, 0.1j),
            Branch("bc", "b", "c", None, 0.1j, 0.1j),
            Branch("ca", "c", "a", None, 0.1j, 0.1j),
        ),
        (Source("grid", "a", None, 0.2j, 0.2j), Source("other", "d", 0.1j, 0.1j, 0.1j)),
        10,
        13.8,
    )
    result = solve_fault(net, "b", "lg")
    np.testing.assert_allclose(result.phase_current_pu, 0, atol=1e-12)
    np.testing.assert_allclose(result.source_current_pu["other"], 0, atol=1e-12)
    assert net.driving_column("b", 1)["b"] == pytest.approx(0.2666666666667j)
    assert net.driving_column("b", 1)["d"] == 0


@pytest.mark.parametrize("fault", FAULT_TYPES)
def test_grounded_mesh_kcl_at_every_bus(fault):
    net = Network(
        ("a", "b", "c"),
        (
            Branch("ab", "a", "b", 0.03 + 0.3j, 0.01 + 0.1j, 0.02 + 0.12j),
            Branch("bc", "b", "c", None, 0.02 + 0.15j, 0.03 + 0.2j),
            Branch("ca", "c", "a", 0.05 + 0.2j, 0.01 + 0.1j, 0.02 + 0.1j),
        ),
        (
            Source("grid", "a", 0.1j, 0.2j, 0.25j),
            Source("generator", "c", None, 0.3j, 0.4j),
        ),
        10,
        13.8,
    )
    result = solve_fault(net, "b", fault, 0.02 + 0.01j)
    assert max(abs(result.phase_current_pu)) > 1
    for bus in net.buses:
        incoming = np.zeros(3, dtype=complex)
        for source in net.sources:
            if source.bus == bus:
                incoming += result.source_current_pu[source.name]
        for branch in net.branches:
            current = result.branch_current_pu[branch.name]
            if branch.from_bus == bus:
                incoming -= current
            if branch.to_bus == bus:
                incoming += current
        expected = result.phase_current_pu if bus == "b" else np.zeros(3)
        np.testing.assert_allclose(incoming, expected, atol=1e-12)


@pytest.mark.parametrize("fault", FAULT_TYPES)
def test_closed_form_thevenin_independent_check(fault):
    # Independent scalar sequence-network formulas, exercised over R+jX values.
    rng = np.random.default_rng(24)
    for _ in range(20):
        z0, z1, z2, zf = rng.uniform(0.01, 0.2, 4) + 1j * rng.uniform(0.05, 0.5, 4)
        e = 1.03 * np.exp(0.12j)
        net = Network(("f",), (), (Source("s", "f", z0, z1, z2),), 100, 138, e)
        if fault == "3ph":
            expected = [0, e / (z1 + zf), 0]
        elif fault == "lg":
            expected = [e / (z0 + z1 + z2 + 3 * zf)] * 3
        elif fault == "ll":
            i1 = e / (z1 + z2 + zf)
            expected = [0, i1, -i1]
        else:
            d = z2 + z0 + 3 * zf
            i1 = e / (z1 + z2 * (z0 + 3 * zf) / d)
            expected = [-i1 * z2 / d, i1, -i1 * (z0 + 3 * zf) / d]
        np.testing.assert_allclose(
            solve_fault(net, "f", fault, zf).sequence_current_pu, expected, atol=1e-12
        )


